// AI summary demo: types itself once visible; screen readers get the full text at once
function Typed({ text }) {
  const reduced = useReducedMotion()
  const [n, setN] = useState(0)
  const [started, setStarted] = useState(false)
  const ref = useInView(() => setStarted(true))
  useEffect(() => {
    if (!started || reduced) return
    let typed = 0
    setN(0)
    const id = setInterval(() => {
      typed += 2
      setN(typed)
      if (typed >= text.length) clearInterval(id)
    }, 22)
    return () => clearInterval(id)
  }, [started, reduced, text])
  const shown = reduced ? text : text.slice(0, n)
  const typing = shown.length < text.length
  return (
    <div ref={ref} className="mt-9 border border-line-2 bg-bg p-6">
      <p className="mb-3 flex items-center gap-2 text-[0.8125rem] font-semibold text-accent">
        <svg viewBox="0 0 24 24" className="size-4" fill="none" stroke="currentColor" strokeWidth="2" strokeLinejoin="round" aria-hidden="true">
          <path d="M12 3l1.9 4.6L18.5 9l-4.6 1.9L12 15.5l-1.9-4.6L5.5 9l4.6-1.4z" />
        </svg>
        <T pt="Resumo gerado · demonstração" en="Generated summary · demo" />
      </p>
      <p className="min-h-[7lh] text-ink">
        <span className="sr-only">{text}</span>
        <span aria-hidden="true">
          {shown}
          {typing && <i className="ml-0.5 inline-block h-[1.1em] w-px translate-y-[0.2em] animate-pulse bg-accent" />}
        </span>
      </p>
    </div>
  )
}

